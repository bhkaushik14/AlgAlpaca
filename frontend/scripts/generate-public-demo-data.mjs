import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const sourceUrl = new URL('../../evaluation/v2_case_results.csv', import.meta.url)
const outputUrl = new URL('../src/publicDemoData.generated.ts', import.meta.url)

const selections = [
  ['confirm-linear-01', 'Linear equations', 'Solve a linear equation'],
  ['confirm-quadratic-01', 'Quadratic equations', 'Find quadratic roots'],
  ['confirm-polynomial-03', 'Polynomial roots', 'Keep radical roots exact'],
  ['confirm-inequality-04', 'Inequalities', 'Solve a product inequality'],
  ['confirm-simplify-04', 'Simplification', 'Simplify radicals'],
  ['confirm-absolute-03', 'Absolute value', 'Compare absolute values'],
]

function parseCsv(input) {
  const rows = []
  let row = []
  let field = ''
  let quoted = false

  for (let index = 0; index < input.length; index += 1) {
    const character = input[index]
    if (quoted) {
      if (character === '"' && input[index + 1] === '"') {
        field += '"'
        index += 1
      } else if (character === '"') {
        quoted = false
      } else {
        field += character
      }
    } else if (character === '"') {
      quoted = true
    } else if (character === ',') {
      row.push(field)
      field = ''
    } else if (character === '\n') {
      row.push(field)
      rows.push(row)
      row = []
      field = ''
    } else if (character !== '\r') {
      field += character
    }
  }

  if (field || row.length) {
    row.push(field)
    rows.push(row)
  }

  const [headers, ...values] = rows
  return values.filter((valuesRow) => valuesRow.length === headers.length).map((valuesRow) =>
    Object.fromEntries(headers.map((header, index) => [header, valuesRow[index]])),
  )
}

const rowsById = new Map(
  parseCsv(readFileSync(sourceUrl, 'utf8')).map((row) => [row.case_id, row]),
)

const cases = selections.map(([id, category, title]) => {
  const row = rowsById.get(id)
  if (!row) throw new Error('Missing selected public-demo case: ' + id)
  if (row.automated_correct !== 'True') {
    throw new Error('Public-demo case is not automated-correct: ' + id)
  }
  if (row.extraction_status !== 'accepted:raw_python' || row.syntax_status !== 'passed' || row.policy_status !== 'passed' || row.execution_status !== 'ok' || row.observable_status !== 'observable') {
    throw new Error('Public-demo case no longer has the expected successful pipeline status: ' + id)
  }

  return {
    id,
    category,
    title,
    problem: row.problem,
    raw_response: row.raw_response,
    extracted_code: row.extracted_code,
    extraction_status: row.extraction_status,
    syntax_status: row.syntax_status,
    policy_status: row.policy_status,
    execution_status: row.execution_status,
    stdout: row.stdout,
    observable_status: row.observable_status,
    parsed_answer: row.parsed_answer,
    automated_correct: true,
    failure_reason: row.failure_reason,
  }
})

const output = '// Generated by scripts/generate-public-demo-data.mjs. Do not edit by hand.\n'
  + '// Source: evaluation/v2_case_results.csv (retained v2 evaluation results).\n\n'
  + "import type { PublicDemoCase } from './types'\n\n"
  + 'export const publicDemoCases = '
  + JSON.stringify(cases, null, 2)
  + ' as const satisfies readonly PublicDemoCase[]\n'
const outputPath = fileURLToPath(outputUrl)

if (process.argv.includes('--check')) {
  if (readFileSync(outputUrl, 'utf8') !== output) {
    throw new Error('Public-demo data is stale. Run npm run demo:data.')
  }
} else {
  writeFileSync(outputPath, output)
}
